export type TranslationKey = keyof typeof fr;

const dictionaries: Record<Locale, Record<TranslationKey, string>> = { fr, en, es, zh, ru };

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[locale]?.[key] ?? dictionaries.fr[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
    template,
  );
}

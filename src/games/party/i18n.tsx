const DICTIONARIES: Record<PartyLocale, Record<Key, string>> = { fr, en, zh };
const CONTENT: Record<PartyLocale, PartyContent> = { fr: FR_CONTENT, en: EN_CONTENT, zh: ZH_CONTENT };

export type PartyT = (key: Key, vars?: Record<string, string | number>) => string;

export function makePartyT(lang: PartyLocale): PartyT {
  const dictionary = DICTIONARIES[lang];
  return (key, vars) => {
    const template = dictionary[key] ?? fr[key];
    if (!vars) return template;
    return Object.entries(vars).reduce((text, [name, value]) => text.split(`{${name}}`).join(String(value)), template);
  };
}

export const PartyLang = createContext<PartyLocale>('fr');

/** Langue, traductions et contenu du jeu d'ambiance en cours. */
export function useParty() {
  const lang = useContext(PartyLang);
  return { lang, t: makePartyT(lang), content: CONTENT[lang] };
}

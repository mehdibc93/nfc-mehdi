const dictionaries: Partial<Record<Locale, Record<Key, string>>> = { fr, en, es };

export type GameTx = (key: Key, vars?: Record<string, string | number>) => string;

export function gameTx(locale: Locale): GameTx {
  const dictionary = dictionaries[locale] ?? en;
  return (key, vars) => {
    const template = dictionary[key] ?? fr[key];
    if (!vars) return template;
    return Object.entries(vars).reduce((text, [name, value]) => text.split(`{${name}}`).join(String(value)), template);
  };
}
